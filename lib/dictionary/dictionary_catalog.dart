final dictionaryWordIds = dictionaryCatalog.map((word) => word.id).toSet();
final budgetWord = dictionaryCatalog.singleWhere((word) => word.id == 'budget');

enum DictionaryFilter { all, read, unread }

String normalizeDictionaryText(String value) =>
    value.trim().toLowerCase().replaceAll('ё', 'е');

List<DictionaryWord> selectDictionaryWords({
  required Set<String> readIds,
  String query = '',
  DictionaryFilter filter = DictionaryFilter.all,
}) {
  final normalized = normalizeDictionaryText(query);
  return dictionaryCatalog.where((word) {
    if (filter == DictionaryFilter.read && !readIds.contains(word.id)) {
      return false;
    }
    if (filter == DictionaryFilter.unread && readIds.contains(word.id)) {
      return false;
    }
    return normalized.isEmpty ||
        [
          word.title,
          ...word.aliases,
        ].any((text) => normalizeDictionaryText(text).contains(normalized));
  }).toList()..sort(
    (a, b) =>
        normalizeDictionaryText(a.title)
            .compareTo(normalizeDictionaryText(b.title)),
  );
}
