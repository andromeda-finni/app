import 'squirrel_game_models.dart';

String normalizedSquirrelPetName(String value) {
  final name = value.trim();
  return name.isEmpty ? squirrelDefaultPetName : name;
}

bool squirrelLevelIntroducesCharacter(SquirrelLevel level) =>
    level == SquirrelLevel.sorting || level == SquirrelLevel.conveyor;

List<String> squirrelIntroLinesFor(
  SquirrelLevel level,
  String petName, {
  bool introduce = true,
}) {
  final name = normalizedSquirrelPetName(petName);
  return switch (level) {
    SquirrelLevel.sorting => [
      if (introduce)
        'Привет, $name! Я Белочка. Мне очень нужно сходить в Магазин, но я совсем не успеваю. Помоги мне, пожалуйста!'
      else
        '$name, начнём с самого важного: отделим свежие продукты от испорченных.',
      'Вот 15 монеток. Нужно купить грибы, ягоды и орехи для зимних запасов.',
      'Рассматривай каждый товар. Свежий клади в корзину, а товар с плохим видом, неприятным запахом или червячком оставь в Магазине.',
    ],
    SquirrelLevel.findOdd => [
      if (introduce)
        'Привет, $name! Я Белочка. Поможешь мне выбрать самые хорошие запасы в Магазине?'
      else
        'Отлично, $name! Часть запасов уже в корзине. Теперь сравним похожие товары.',
      'Продавец выложил по три гриба, ягоды и ореха. В каждой группе только один товар хороший.',
      'Не спеши: сравни цвет, целостность и внешний вид, а потом выбирай.',
    ],
    SquirrelLevel.conveyor => [
      if (introduce)
        'Привет, $name! Я Белочка. Мне очень нужно сходить в Магазин, но я совсем не успеваю. Помоги мне, пожалуйста!'
      else
        '$name, теперь нам нужно быстро собрать список покупок и не выйти за рамки бюджета.',
      'В списке: два хороших гриба, одна свежая ягода и один целый орех. На покупки есть 20 монет.',
      'Товары появляются на прилавке один за другим. Перетаскивай в корзину только то, что есть в списке и хорошо выглядит.',
    ],
    SquirrelLevel.inspect => [
      if (introduce)
        'Привет, $name! Я Белочка. В Магазине товары иногда кладут красивой стороной вверх. Поможешь мне всё проверить?'
      else
        'Мы почти закончили, $name! Осталась самая хитрая проверка.',
      'С одной стороны товар может выглядеть идеально, а с другой могут быть пятно, неприятный запах или трещина.',
      'Сначала нажми на товар и поверни его. Покупай только после осмотра.',
    ],
  };
}

