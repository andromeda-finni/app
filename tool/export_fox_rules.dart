import 'dart:convert';
import 'dart:io';

import 'package:andromeda_app/events/fox/fox_event_content.dart';

/// Export only server-authoritative transitions; the authored story stays in Dart.
void main() {
  final rules = {
    for (final script in kFoxScripts)
      script.id: {
        'ageGroup': script.ageGroup.name,
        'initialNodeId': script.initialNodeId,
        'nodes': {
          for (final node in script.nodes.values)
            node.id: {
              'terminal': node.terminal,
              'waitUntilNextGameDay': node.waitUntilNextGameDay,
              'coinDeltaOnEnter': node.coinDeltaOnEnter,
              'choices': {
                for (final choice in node.choices)
                  choice.id: {
                    'nextNodeId': choice.nextNodeId,
                    'coinDelta': choice.coinDelta,
                  },
              },
            },
        },
      },
  };
  File('backend/src/modules/foxEvents/content.ts')
    ..createSync(recursive: true)
    ..writeAsStringSync(
      '// Generated by dart tool/export_fox_rules.dart. Do not edit by hand.\n'
      'export const foxScripts = ${const JsonEncoder.withIndent('  ').convert(rules)} as const;\n',
    );
}
